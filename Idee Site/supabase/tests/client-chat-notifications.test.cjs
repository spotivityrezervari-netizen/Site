// Real disposable PostgreSQL/RLS. No hosted credentials, HTTP calls or emails.
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {createFixture,uid}=require('./club-request-fixture.cjs');
const sql=name=>readFileSync(join(__dirname,'..',name),'utf8');
const denied=error=>error.code==='42501'||/permission denied/.test(error.message);

test('client chat email outbox preserves ownership and cuts over legacy staff replies atomically',async t=>{
 const fixture=await createFixture(),{pg}=fixture;
 const as=(role,person,query,params=[])=>fixture.serial(async()=>{
  await pg.exec('reset role');
  await pg.query("select set_config('request.jwt.claim.sub',$1,false)",[person?uid(person):'']);
  await pg.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({role,sub:person?uid(person):null})]);
  await pg.exec(`set role ${role}`);return pg.query(query,params);
 });
 const root=(query,params=[])=>as('postgres',null,query,params);
 const jobs=()=>root("select * from spotivity_private.notification_outbox where kind='chat_client' order by created_at,id").then(r=>r.rows);
 const payload=id=>root('select spotivity_private.notification_payload($1) value',[id]).then(r=>r.rows[0].value);
 const context=(person,id)=>as('authenticated',person,'select public.get_email_chat_context($1::text) value',[id]).then(r=>r.rows[0].value);
 const send=async(person,court,text,email='alice@example.test')=>(await as('authenticated',person,"insert into public.mesaje_chat(email_client,teren,expeditor,mesaj) values($1,$2,'admin',$3) returning id::text id",[email,court,text])).rows[0].id;
 const business=async()=>{
  const result={};
  for(const table of ['auth.users','public.clienti','public.users_admin','public.terenuri','public.rezervari','public.mesaje_chat','public.baze_sportive','spotivity_private.booking_groups','spotivity_private.notification_outbox'])result[table]=(await root(`select to_jsonb(t) row from ${table} t order by to_jsonb(t)::text`)).rows;
  return result;
 };
 let a,b,oldMessage,newMessage,newJob;
 try{
  if(process.env.SPOTIVITY_TEST_NUMERIC_CHAT_ID==='1')await fixture.root(()=>pg.exec(`
   alter table public.mesaje_chat alter column id drop default;
   alter table public.mesaje_chat alter column id type bigint using null::bigint;
   alter table public.mesaje_chat alter column id add generated by default as identity;
   grant usage,select on sequence public.mesaje_chat_id_seq to authenticated,service_role;`));
  await root("alter table auth.users add column created_at timestamptz not null default '2000-01-01T00:00:00Z',add column deleted_at timestamptz,add column banned_until timestamptz;");
  for(const name of ['021_account_welcome.sql','022_email_booking_context.sql','023_late_cancellations.sql'])await fixture.root(()=>pg.exec(sql(name)));
  const courts=(await root('select id::text id,nume from public.terenuri')).rows;
  a=courts.find(c=>c.nume==='Court A').id;b=courts.find(c=>c.nume==='Court B').id;
  await root("update public.clienti set telefon=case when user_id=$1 then '0712345678' else '0799999999' end",[uid(1)]);
  const day=(await root("select ((now() at time zone 'Europe/Bucharest')::date+2)::text booking_day")).rows[0].booking_day;
  await as('authenticated',1,'select public.create_booking_group($1,$2,$3::date,$4::text[],false)',[uid(2401),a,day,['12:00']]);
  await as('authenticated',2,'select public.create_booking_group($1,$2,$3::date,$4::text[],false)',[uid(2402),b,day,['14:00']]);
  await fixture.root(()=>pg.exec(`create schema if not exists supabase_functions;
   create table spotivity_private.legacy_chat_probe(message_id text,args text[]);
   create function supabase_functions.http_request() returns trigger language plpgsql security definer set search_path='' as $$ begin insert into spotivity_private.legacy_chat_probe values(new.id::text,TG_ARGV);return new;end $$;
   create trigger "webhook-chat-nou" after insert on public.mesaje_chat for each row when(new.expeditor is distinct from 'client') execute function supabase_functions.http_request('https://example.test/controlled-private-hook','POST','{}','{}','5000');`));
  oldMessage=await send(3,'Court A','Răspuns istoric');
  const before=await business();
  await fixture.root(()=>pg.exec(sql('024_client_chat_notifications.sql')));

  await t.test('migration preserves every business row, creates no historical client notifications and is idempotent',async()=>{
   assert.deepEqual(await business(),before);assert.deepEqual(await jobs(),[]);
   await fixture.root(()=>pg.exec(sql('024_client_chat_notifications.sql')));assert.deepEqual(await business(),before);
   assert.equal((await root('select count(*)::int n from spotivity_private.migrations where version=24')).rows[0].n,1);
  });
  await t.test('authorized staff reply queues exactly one client notification and suppresses its legacy webhook',async()=>{
   newMessage=await send(3,'Court A','Da, vestiarul este disponibil.');
   const all=await jobs();assert.equal(all.length,1);newJob=all[0];
   assert.equal(newJob.chat_id,newMessage);assert.equal(newJob.recipient_user_id,uid(1));assert.equal(newJob.booking_id,null);
   assert.equal(newJob.event_key,newMessage);assert.equal(newJob.recipient_key,uid(1));
   assert.equal((await root('select count(*)::int n from spotivity_private.legacy_chat_probe')).rows[0].n,1);
   assert.ok(!JSON.stringify(newJob).includes('alice@example.test'));assert.ok(!JSON.stringify(newJob).includes('vestiarul'));
   const p=await payload(newJob.id);assert.equal(p.kind,'chat_client');assert.equal(p.recipient.email,'alice@example.test');
   assert.equal(p.chat.messageID,newMessage);assert.equal(p.chat.preview,'Da, vestiarul este disponibil.');assert.equal(p.chat.courtName,'Court A');
   assert.ok(!JSON.stringify(p).includes('cancellation'));assert.ok(!JSON.stringify(p).includes('access_token'));
  });
  await t.test('legacy null-account replies keep their destination and original trigger arguments',async()=>{
   await root("insert into public.mesaje_chat(email_client,teren,expeditor,mesaj) values('legacy@example.test','Court A','admin','Legacy without account id')");
   const rows=(await root('select * from spotivity_private.legacy_chat_probe order by message_id')).rows;
   assert.equal(rows.length,2);assert.deepEqual(rows[0].args,['https://example.test/controlled-private-hook','POST','{}','{}','5000']);
   const definition=(await root("select pg_get_triggerdef(oid) value from pg_trigger where tgname='webhook-chat-nou'")).rows[0].value;
   assert.match(definition,/client_user_id IS NULL/);assert.match(definition,/expeditor IS DISTINCT FROM 'client'/);
   assert.equal((await jobs()).length,1);
  });
  await t.test('client messages still produce owner notifications while read receipts never enqueue another email',async()=>{
   const ownersBefore=(await root("select count(*)::int n from spotivity_private.notification_outbox where kind='chat_owner'")).rows[0].n;
   await as('authenticated',1,"insert into public.mesaje_chat(email_client,teren,expeditor,mesaj) values('alice@example.test','Court A','client','Mulțumesc!')");
   assert.equal((await root("select count(*)::int n from spotivity_private.notification_outbox where kind='chat_owner'")).rows[0].n,ownersBefore+1);
   await as('authenticated',1,'update public.mesaje_chat set citit=true where id::text=$1',[newMessage]);
   assert.equal((await jobs()).length,1);
  });
  await t.test('the verified client opens its message context; other clients and unknown ids get identical denial',async()=>{
   const c=await context(1,newMessage);assert.equal(c.message_id,newMessage);assert.equal(c.court_id,a);assert.equal(c.court_name,'Court A');
   assert.equal(c.customer_email,'alice@example.test');assert.equal(c.is_owner,false);assert.ok(!JSON.stringify(c).includes('token'));
   let unrelated,unknown;try{await context(2,newMessage);}catch(e){unrelated=e;}try{await context(2,uid(999999));}catch(e){unknown=e;}
   assert.equal(unrelated.code,'42501');assert.equal(unknown.code,'42501');assert.equal(unrelated.message,unknown.message);
   for(const id of ['',null,'../other','1 OR 1=1','0001','9'.repeat(21)])await assert.rejects(()=>context(1,id),denied);
  });
  await t.test('staff context observes current allocation and superadmin privileges without changing client ownership',async()=>{
   assert.equal((await context(3,newMessage)).is_owner,true);assert.equal((await context(4,newMessage)).is_owner,true);
   await root("update public.users_admin set terenuri='Court B' where user_id=$1",[uid(3)]);
   await assert.rejects(()=>context(3,newMessage),denied);assert.equal((await context(1,newMessage)).is_owner,false);
   await root("update public.users_admin set terenuri='Court A' where user_id=$1",[uid(3)]);
   await assert.rejects(()=>send(3,'Court B','Should not reach Bob','bob@example.test'));
  });
  await t.test('recipient is re-resolved from the current verified Auth identity, never a URL or copied email',async()=>{
   await root("update auth.users set email='alice-changed@example.test' where id=$1",[uid(1)]);
   assert.equal((await payload(newJob.id)).recipient.email,'alice-changed@example.test');
   assert.equal((await context(1,newMessage)).customer_email,'alice-changed@example.test');
   await root('update auth.users set email_confirmed_at=null where id=$1',[uid(1)]);
   assert.equal(await payload(newJob.id),null);await assert.rejects(()=>context(1,newMessage),denied);
   await root('update auth.users set email_confirmed_at=now() where id=$1',[uid(1)]);
   await root('update auth.users set banned_until=now()+interval \'1 day\' where id=$1',[uid(1)]);
   assert.equal(await payload(newJob.id),null);await root('update auth.users set banned_until=null where id=$1',[uid(1)]);
   await root('update auth.users set deleted_at=now() where id=$1',[uid(1)]);assert.equal(await payload(newJob.id),null);
   await root('update auth.users set deleted_at=null where id=$1',[uid(1)]);
  });
  await t.test('disabled chat or missing booking suppresses delivery and cannot expose a conversation',async()=>{
   await root('update public.terenuri set are_chat=false where id::text=$1',[a]);
   assert.equal(await payload(newJob.id),null);await assert.rejects(()=>context(1,newMessage),denied);
   await root('update public.terenuri set are_chat=true where id::text=$1',[a]);
   const current=await payload(newJob.id);assert.equal(current.chat.messageID,newMessage);
   await root('begin');await pg.query('delete from public.rezervari where client_user_id=$1 and teren=$2',[uid(1),'Court A']);
   assert.equal((await pg.query('select spotivity_private.notification_payload($1) value',[newJob.id])).rows[0].value,null);await pg.exec('rollback');
  });
  await t.test('anonymous/service callers cannot open authenticated context or access private jobs',async()=>{
   for(const role of ['anon','authenticated','service_role']){
    await assert.rejects(()=>as(role,role==='authenticated'?1:null,'select * from spotivity_private.notification_outbox'),denied);
    await assert.rejects(()=>as(role,role==='authenticated'?1:null,'select spotivity_private.notification_payload_v23($1)',[newJob.id]),denied);
    if(role!=='authenticated')await assert.rejects(()=>as(role,null,'select public.get_email_chat_context($1)',[newMessage]),denied);
   }
   assert.equal((await root("select relrowsecurity from pg_class where oid='spotivity_private.notification_outbox'::regclass")).rows[0].relrowsecurity,true);
  });
  await t.test('only service leases chat_client once, and an acknowledged job cannot be leased again',async()=>{
   const [claimed]=(await as('service_role',null,"select value from public.claim_booking_notifications(20,120,null,array['chat_client']) value")).rows.map(r=>r.value);
   assert.equal(claimed.kind,'chat_client');assert.equal(claimed.chat.messageID,newMessage);assert.ok(claimed.lease_token);
   assert.equal((await as('service_role',null,"select * from public.claim_booking_notifications(20,120,null,array['chat_client'])")).rows.length,0);
   assert.equal((await as('service_role',null,"select public.finish_booking_notification($1,$2,'submitted') value",[claimed.notification_id,claimed.lease_token])).rows[0].value,true);
   assert.equal((await as('service_role',null,"select * from public.claim_booking_notifications(20,120,null,array['chat_client'])")).rows.length,0);
  });
  await t.test('booking, welcome and owner-chat payload branches retain exactly the previous payload',async()=>{
   const ids=(await root("select id from spotivity_private.notification_outbox where kind<>'chat_client'")).rows.map(r=>r.id);
   for(const id of ids){
    const now=await payload(id),previous=(await root('select spotivity_private.notification_payload_v23($1) value',[id])).rows[0].value;
    assert.deepEqual(now,previous);
   }
   assert.equal((await jobs()).length,1);
  });
 }finally{await fixture.close();}
});
